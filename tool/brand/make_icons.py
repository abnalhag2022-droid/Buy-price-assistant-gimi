#!/usr/bin/env python3
"""Generate the launcher icon resources and SVG brand sources from one geometry.

Outputs (committed, so builds do not depend on running this script):
  tool/android_res/drawable/hji_launcher_icon.xml           legacy icon (Android 7)
  tool/android_res/drawable-anydpi-v26/hji_launcher_icon.xml adaptive icon (Android 8+)
  tool/android_res/drawable/hji_launcher_{background,foreground,monochrome}.xml
  tool/brand/icon.svg, tool/brand/icon_foreground.svg       for store assets

Geometry: a white receipt with three navy lines and a gold coin with a navy
dollar sign, on navy (#18365F). Canvas 108x108 as Android adaptive icons.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "tool" / "android_res"
BRAND = ROOT / "tool" / "brand"

NAVY = "#18365F"
GOLD = "#F6C453"
WHITE = "#FFFFFF"

RECEIPT = "M25,20h45a5,5 0 0 1 5,5v55l-8,-5 -8,5 -8,-5 -8,5 -8,-5 -10,5z"
LINES = "M35,31h25v4h-25zM35,42h25v4h-25zM35,53h18v4h-18z"
COIN = "M97,71a22,22 0 1 1,-44 0a22,22 0 1 1,44 0z"
# Dollar sign drawn around (72.5, 52); placed at the coin centre (75, 71).
DOLLAR_SOURCE = ("M83,39c-2,-3 -5,-5 -9,-5 -6,0 -10,3 -10,8 0,5 4,7 10,9 4,1 5,2 5,4 0,2 -2,4 -6,4 "
                 "-4,0 -7,-2 -9,-4l-3,4c2,3 5,5 9,6v5h5v-5c6,-1 9,-5 9,-10 0,-5 -4,-8 -10,-10 "
                 "-4,-1 -5,-2 -5,-3 0,-2 2,-3 5,-3 3,0 5,1 7,3z")


def transform_path(path: str, scale: float, pivot: tuple[float, float], to: tuple[float, float]) -> str:
    """Scales a path that uses an absolute M and relative c/l/v/h segments."""
    tokens = re.findall(r"[MmCcLlVvHhZz]|-?\d+(?:\.\d+)?", path)
    out: list[str] = []
    command = ""
    numbers: list[float] = []

    def flush() -> None:
        if not command:
            return
        if command == "M":
            x, y = numbers
            out.append(f"M{to[0] + (x - pivot[0]) * scale:.2f},{to[1] + (y - pivot[1]) * scale:.2f}")
        elif command in "clvh":
            values = " ".join(f"{n * scale:.2f}" for n in numbers)
            out.append(f"{command}{values}")
        elif command in "zZ":
            out.append("z")

    for token in tokens:
        if re.fullmatch(r"[A-Za-z]", token):
            flush()
            command, numbers = token, []
        else:
            numbers.append(float(token))
    flush()
    return "".join(out)


DOLLAR = transform_path(DOLLAR_SOURCE, 0.72, (72.5, 52.0), (75.0, 71.0))

# Content box of the drawing: x 25..97, y 20..93, centre (61, 56.5).
CENTRE = (61.0, 56.5)


def group(scale: float, body: str) -> str:
    """Scales the drawing around its centre and moves it to the canvas centre."""
    return (f'    <group android:pivotX="{CENTRE[0]}" android:pivotY="{CENTRE[1]}" '
            f'android:scaleX="{scale}" android:scaleY="{scale}" '
            f'android:translateX="{54 - CENTRE[0]}" android:translateY="{54 - CENTRE[1]}">\n{body}    </group>\n')


def vector(body: str) -> str:
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tool/brand/make_icons.py; edit the script, not this file. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f'{body}</vector>\n')


def path(fill: str, data: str, even_odd: bool = False) -> str:
    rule = ' android:fillType="evenOdd"' if even_odd else ""
    return f'        <path android:fillColor="{fill}"{rule} android:pathData="{data}"/>\n'


def artwork() -> str:
    return path(WHITE, RECEIPT) + path(NAVY, LINES) + path(GOLD, COIN) + path(NAVY, DOLLAR)


def write(target: Path, content: str) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)}")


def svg(body: str, background: bool, scale: float) -> str:
    tx, ty = 54 - CENTRE[0], 54 - CENTRE[1]
    transform = (f"translate({tx + CENTRE[0]} {ty + CENTRE[1]}) scale({scale}) "
                 f"translate({-CENTRE[0]} {-CENTRE[1]})")
    back = f'<rect width="108" height="108" fill="{NAVY}"/>' if background else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{back}'
            f'<g transform="{transform}">{body}</g></svg>\n')


def main() -> None:
    # Adaptive icons show the centre 72dp of 108dp and keep 66dp safe from any
    # mask, so the drawing is scaled to fit a 66dp circle.
    adaptive_scale = 0.62
    legacy_scale = 0.86
    write(RES / "drawable" / "hji_launcher_background.xml",
          vector(f'    <path android:fillColor="{NAVY}" android:pathData="M0,0h108v108h-108z"/>\n'))
    write(RES / "drawable" / "hji_launcher_foreground.xml", vector(group(adaptive_scale, artwork())))
    # Themed icons (Android 13+) use only the alpha of this layer; the lines and
    # the dollar sign are cut out with the even-odd rule.
    write(RES / "drawable" / "hji_launcher_monochrome.xml",
          vector(group(adaptive_scale, path(WHITE, RECEIPT + LINES, even_odd=True) + path(WHITE, COIN + DOLLAR, even_odd=True))))
    write(RES / "drawable" / "hji_launcher_icon.xml",
          vector(f'    <path android:fillColor="{NAVY}" android:pathData="M0,0h108v108h-108z"/>\n'
                 + group(legacy_scale, artwork())))
    write(RES / "drawable-anydpi-v26" / "hji_launcher_icon.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tool/brand/make_icons.py; edit the script, not this file. -->\n'
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@drawable/hji_launcher_background"/>\n'
          '    <foreground android:drawable="@drawable/hji_launcher_foreground"/>\n'
          '    <monochrome android:drawable="@drawable/hji_launcher_monochrome"/>\n'
          '</adaptive-icon>\n')
    svg_body = (f'<path fill="{WHITE}" d="{RECEIPT}"/><path fill="{NAVY}" d="{LINES}"/>'
                f'<path fill="{GOLD}" d="{COIN}"/><path fill="{NAVY}" d="{DOLLAR}"/>')
    write(BRAND / "icon.svg", svg(svg_body, background=True, scale=0.78))
    write(BRAND / "icon_foreground.svg", svg(svg_body, background=False, scale=1.0))


if __name__ == "__main__":
    main()
